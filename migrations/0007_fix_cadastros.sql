-- Correção de cadastros da Versão 1 - DMS ROTA.
-- Preserva os registros existentes e alinha unicidade/terceiros ao comportamento da v2.0.44.

DROP TABLE IF EXISTS BASE_COLABORADORES_V1_FIX;
CREATE TABLE BASE_COLABORADORES_V1_FIX (
  ID TEXT PRIMARY KEY,
  MATRICULA TEXT,
  NOME TEXT NOT NULL,
  FUNCAO TEXT NOT NULL,
  VINCULO TEXT,
  STATUS TEXT NOT NULL DEFAULT 'DISPONÍVEL',
  AJUDANTE_ROTA INTEGER NOT NULL DEFAULT 0 CHECK (AJUDANTE_ROTA IN (0,1)),
  CIDADE_ROTA TEXT,
  ROTAS_ATENDIDAS TEXT,
  FERIAS_INICIO TEXT,
  FERIAS_FIM TEXT,
  ANOMALIA TEXT,
  OBSERVACOES TEXT,
  UNIDADE TEXT,
  DATA_ADMISSAO TEXT,
  HORA_ENTRADA_PADRAO TEXT,
  JORNADA_CONTRATUAL_MIN INTEGER,
  ATIVO INTEGER NOT NULL DEFAULT 1 CHECK (ATIVO IN (0,1)),
  CRIADO_EM TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP,
  ATUALIZADO_EM TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP,
  USUARIO TEXT
);
INSERT INTO BASE_COLABORADORES_V1_FIX
SELECT ID,NULLIF(TRIM(MATRICULA),''),NOME,FUNCAO,VINCULO,STATUS,AJUDANTE_ROTA,CIDADE_ROTA,ROTAS_ATENDIDAS,
       FERIAS_INICIO,FERIAS_FIM,ANOMALIA,OBSERVACOES,UNIDADE,DATA_ADMISSAO,HORA_ENTRADA_PADRAO,
       JORNADA_CONTRATUAL_MIN,ATIVO,CRIADO_EM,ATUALIZADO_EM,USUARIO
FROM BASE_COLABORADORES;
DROP TABLE BASE_COLABORADORES;
ALTER TABLE BASE_COLABORADORES_V1_FIX RENAME TO BASE_COLABORADORES;
CREATE INDEX IDX_ROUTE_COLAB_NOME ON BASE_COLABORADORES(NOME);
CREATE INDEX IDX_ROUTE_COLAB_FUNCAO_STATUS ON BASE_COLABORADORES(FUNCAO,STATUS,ATIVO);
CREATE UNIQUE INDEX UQ_ROUTE_COLAB_MATRICULA_ACTIVE
  ON BASE_COLABORADORES(UPPER(TRIM(MATRICULA)))
  WHERE ATIVO=1 AND MATRICULA IS NOT NULL AND TRIM(MATRICULA)<>'';

