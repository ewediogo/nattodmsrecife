-- Histórico de localizações e base futura de clientes para o mapa da Rota.
CREATE TABLE IF NOT EXISTS ROUTE_GPS_POSITIONS (
  ID INTEGER PRIMARY KEY AUTOINCREMENT,
  PLATE TEXT NOT NULL,
  LATITUDE REAL,
  LONGITUDE REAL,
  GPS_TIME TEXT NOT NULL,
  FETCHED_AT TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP,
  LOCATION_TEXT TEXT,
  POINT_TEXT TEXT,
  SPEED REAL NOT NULL DEFAULT 0,
  IGNITION INTEGER NOT NULL DEFAULT 0,
  VEHICLE_ID TEXT,
  VEHICLE_TYPE TEXT,
  RAW_JSON TEXT,
  CREATED_AT TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP,
  UNIQUE(PLATE,GPS_TIME,LATITUDE,LONGITUDE)
);
CREATE INDEX IF NOT EXISTS IDX_ROUTE_GPS_PLATE_TIME ON ROUTE_GPS_POSITIONS(PLATE,GPS_TIME DESC);

CREATE TABLE IF NOT EXISTS BASE_CLIENTES (
  ID TEXT PRIMARY KEY,
  CODIGO TEXT,
  NOME TEXT NOT NULL,
  LATITUDE REAL NOT NULL,
  LONGITUDE REAL NOT NULL,
  RAIO_METROS REAL NOT NULL DEFAULT 100,
  CIDADE TEXT,
  UF TEXT,
  ENDERECO TEXT,
  OBSERVACOES TEXT,
  ATIVO INTEGER NOT NULL DEFAULT 1,
  CRIADO_EM TEXT,
  ATUALIZADO_EM TEXT,
  USUARIO TEXT
);
CREATE INDEX IF NOT EXISTS IDX_BASE_CLIENTES_ATIVO ON BASE_CLIENTES(ATIVO,NOME);
