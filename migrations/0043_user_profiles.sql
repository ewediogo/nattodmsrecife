-- Perfil do usuário (menu: avatar > Meu perfil). Idempotente; a API também cria sob demanda.
CREATE TABLE IF NOT EXISTS ROUTE_USER_PROFILES (
  USER_ID INTEGER PRIMARY KEY,
  PHONE TEXT,
  UNIT TEXT,
  DEPARTMENT TEXT,
  BIRTHDATE TEXT,
  BIO TEXT,
  WORK_START TEXT,
  WORK_END TEXT,
  WORK_BREAK_MIN INTEGER,
  WORK_DAYS TEXT,
  AVATAR_DATA TEXT,
  UPDATED_AT TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP
);
