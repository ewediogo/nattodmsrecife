-- Histórico de chegada/saída em clientes identificado pelas posições GPS.
-- Um registro permanece aberto enquanto o veículo estiver dentro do raio do mesmo cliente.
CREATE TABLE IF NOT EXISTS ROUTE_CLIENT_ARRIVALS (
  ID INTEGER PRIMARY KEY AUTOINCREMENT,
  SCHEDULE_ID TEXT NOT NULL,
  PLATE TEXT NOT NULL,
  CLIENT_ID TEXT NOT NULL,
  CLIENT_NAME TEXT NOT NULL,
  ARRIVED_AT TEXT NOT NULL,
  LAST_SEEN_AT TEXT NOT NULL,
  LEFT_AT TEXT,
  LATITUDE REAL,
  LONGITUDE REAL,
  ARRIVAL_DISTANCE_METERS INTEGER,
  CREATED_AT TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP,
  UPDATED_AT TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE UNIQUE INDEX IF NOT EXISTS IDX_ROUTE_CLIENT_ARRIVAL_OPEN
  ON ROUTE_CLIENT_ARRIVALS(SCHEDULE_ID,PLATE,CLIENT_ID)
  WHERE LEFT_AT IS NULL;
CREATE INDEX IF NOT EXISTS IDX_ROUTE_CLIENT_ARRIVAL_SCHEDULE
  ON ROUTE_CLIENT_ARRIVALS(SCHEDULE_ID,ARRIVED_AT);
CREATE INDEX IF NOT EXISTS IDX_ROUTE_CLIENT_ARRIVAL_PLATE
  ON ROUTE_CLIENT_ARRIVALS(PLATE,ARRIVED_AT);
