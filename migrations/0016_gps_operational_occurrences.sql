-- Ocorrências automáticas temporárias do GPS: apenas parada >15 min e ignição desligada 20:00-05:00.
CREATE TABLE IF NOT EXISTS ROUTE_GPS_OCCURRENCES (
  OCCURRENCE_KEY TEXT PRIMARY KEY,
  TYPE TEXT NOT NULL,
  PRIORITY TEXT NOT NULL DEFAULT 'MÉDIA',
  DATE_KEY TEXT NOT NULL,
  PLATE TEXT NOT NULL,
  ROUTE TEXT,
  DRIVER_NAME TEXT,
  SCHEDULE_ID TEXT,
  MONITORING_ID INTEGER,
  STARTED_AT TEXT,
  DETECTED_AT TEXT NOT NULL,
  LAST_SEEN_AT TEXT NOT NULL,
  LOCATION_TEXT TEXT,
  LATITUDE REAL,
  LONGITUDE REAL,
  STOPPED_MINUTES INTEGER NOT NULL DEFAULT 0,
  IGNITION INTEGER NOT NULL DEFAULT 0,
  DETAILS TEXT,
  DATA_JSON TEXT,
  CREATED_AT TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP,
  UPDATED_AT TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS IDX_ROUTE_GPS_OCC_DATE ON ROUTE_GPS_OCCURRENCES(DATE_KEY,TYPE,PLATE);
