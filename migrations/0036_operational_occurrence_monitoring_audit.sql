-- v1.0.131 - Auditoria de tratativa das ocorrências operacionais.
-- Preserva o primeiro horário de justificativa na tabela principal e registra cada alteração.
CREATE TABLE IF NOT EXISTS ROUTE_OPERATIONAL_JUSTIFICATION_HISTORY (
  ID INTEGER PRIMARY KEY AUTOINCREMENT,
  OCCURRENCE_KEY TEXT NOT NULL,
  JUSTIFICATION TEXT NOT NULL,
  JUSTIFIED_BY_ID INTEGER,
  JUSTIFIED_BY_NAME TEXT,
  RECORDED_AT TEXT NOT NULL,
  ACTION TEXT NOT NULL DEFAULT 'REGISTRO'
);
CREATE INDEX IF NOT EXISTS IDX_ROUTE_OPERATIONAL_JUST_HISTORY_KEY
  ON ROUTE_OPERATIONAL_JUSTIFICATION_HISTORY(OCCURRENCE_KEY, RECORDED_AT);
