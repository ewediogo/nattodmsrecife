-- Justificativas de ocorrências automáticas da auditoria operacional.
-- A contagem operacional passa a considerar ocorrências a partir de 21/08/2026.
CREATE TABLE IF NOT EXISTS ROUTE_OPERATIONAL_JUSTIFICATIONS (
  OCCURRENCE_KEY TEXT PRIMARY KEY,
  JUSTIFICATION TEXT NOT NULL,
  JUSTIFIED_BY_ID INTEGER,
  JUSTIFIED_BY_NAME TEXT,
  JUSTIFIED_AT TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP,
  UPDATED_AT TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS IDX_ROUTE_OPERATIONAL_JUSTIFICATIONS_AT
  ON ROUTE_OPERATIONAL_JUSTIFICATIONS(JUSTIFIED_AT);
