CREATE TABLE IF NOT EXISTS LINCROS_DAY_SYNC (
  DATE_KEY TEXT PRIMARY KEY,
  ROUTE_COUNT INTEGER NOT NULL DEFAULT 0,
  CHECKED_AT TEXT,
  SYNCED_AT TEXT,
  DATA_HASH TEXT,
  LAST_ERROR TEXT
);
CREATE TABLE IF NOT EXISTS LINCROS_DAY_ROUTES (
  DATE_KEY TEXT NOT NULL,
  ROUTE_CODE TEXT NOT NULL,
  PLATE TEXT,
  SOURCE_UPDATED_AT TEXT,
  ROUTE_JSON TEXT NOT NULL,
  PRIMARY KEY(DATE_KEY,ROUTE_CODE)
);
CREATE INDEX IF NOT EXISTS IDX_LINCROS_DAY_ROUTES_PLATE ON LINCROS_DAY_ROUTES(DATE_KEY,PLATE);
