-- Rastreabilidade de edição manual nos cadastros operacionais.
ALTER TABLE BASE_COLABORADORES ADD COLUMN ATUALIZADO_POR TEXT;
ALTER TABLE BASE_VEICULOS ADD COLUMN ATUALIZADO_POR TEXT;

UPDATE BASE_COLABORADORES
SET ATUALIZADO_POR=COALESCE(NULLIF(TRIM(ATUALIZADO_POR),''),NULLIF(TRIM(USUARIO),''),'Sistema')
WHERE COALESCE(NULLIF(TRIM(ATUALIZADO_POR),''),'')='';

UPDATE BASE_VEICULOS
SET ATUALIZADO_POR=COALESCE(NULLIF(TRIM(ATUALIZADO_POR),''),NULLIF(TRIM(USUARIO),''),'Sistema')
WHERE COALESCE(NULLIF(TRIM(ATUALIZADO_POR),''),'')='';
