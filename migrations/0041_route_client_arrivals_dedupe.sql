-- Corrige duplicidades históricas no marco de chegada/saída de clientes.
-- Mantém um único registro por viagem/placa/cliente/horário de chegada, preservando
-- o maior LAST_SEEN_AT e a saída mais recente entre os registros repetidos.

UPDATE ROUTE_CLIENT_ARRIVALS
SET LAST_SEEN_AT = (
      SELECT MAX(COALESCE(X.LAST_SEEN_AT,''))
      FROM ROUTE_CLIENT_ARRIVALS X
      WHERE X.SCHEDULE_ID=ROUTE_CLIENT_ARRIVALS.SCHEDULE_ID
        AND X.PLATE=ROUTE_CLIENT_ARRIVALS.PLATE
        AND X.CLIENT_ID=ROUTE_CLIENT_ARRIVALS.CLIENT_ID
        AND X.ARRIVED_AT=ROUTE_CLIENT_ARRIVALS.ARRIVED_AT
    ),
    LEFT_AT = NULLIF((
      SELECT MAX(COALESCE(X.LEFT_AT,''))
      FROM ROUTE_CLIENT_ARRIVALS X
      WHERE X.SCHEDULE_ID=ROUTE_CLIENT_ARRIVALS.SCHEDULE_ID
        AND X.PLATE=ROUTE_CLIENT_ARRIVALS.PLATE
        AND X.CLIENT_ID=ROUTE_CLIENT_ARRIVALS.CLIENT_ID
        AND X.ARRIVED_AT=ROUTE_CLIENT_ARRIVALS.ARRIVED_AT
    ),'')
WHERE ID IN (
  SELECT MIN(ID)
  FROM ROUTE_CLIENT_ARRIVALS
  GROUP BY SCHEDULE_ID,PLATE,CLIENT_ID,ARRIVED_AT
  HAVING COUNT(*)>1
);

DELETE FROM ROUTE_CLIENT_ARRIVALS
WHERE EXISTS (
  SELECT 1
  FROM ROUTE_CLIENT_ARRIVALS K
  WHERE K.ID<ROUTE_CLIENT_ARRIVALS.ID
    AND K.SCHEDULE_ID=ROUTE_CLIENT_ARRIVALS.SCHEDULE_ID
    AND K.PLATE=ROUTE_CLIENT_ARRIVALS.PLATE
    AND K.CLIENT_ID=ROUTE_CLIENT_ARRIVALS.CLIENT_ID
    AND K.ARRIVED_AT=ROUTE_CLIENT_ARRIVALS.ARRIVED_AT
);

CREATE UNIQUE INDEX IF NOT EXISTS IDX_ROUTE_CLIENT_ARRIVAL_EVENT
  ON ROUTE_CLIENT_ARRIVALS(SCHEDULE_ID,PLATE,CLIENT_ID,ARRIVED_AT);
