-- Histórico corrente do último motorista associado a cada placa.
-- Aplicar depois da 0020_ignition_off_night_3_4.sql.

CREATE TABLE IF NOT EXISTS ROUTE_VEHICLE_LAST_DRIVER (
  PLATE TEXT PRIMARY KEY,
  VEHICLE_ID TEXT,
  DRIVER_ID TEXT,
  DRIVER_NAME TEXT NOT NULL,
  SCHEDULE_ID TEXT,
  EFFECTIVE_AT TEXT NOT NULL,
  UPDATED_AT TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS IDX_ROUTE_VEHICLE_LAST_DRIVER_DRIVER
  ON ROUTE_VEHICLE_LAST_DRIVER(DRIVER_ID, EFFECTIVE_AT);

-- Backfill imediato: ao aplicar a migration, a Central já mostra o motorista mais
-- recente conhecido de cada placa, sem esperar uma nova escala ser salva.
INSERT INTO ROUTE_VEHICLE_LAST_DRIVER
  (PLATE,VEHICLE_ID,DRIVER_ID,DRIVER_NAME,SCHEDULE_ID,EFFECTIVE_AT,UPDATED_AT)
SELECT PLATE_KEY,VEICULO_ID,MOTORISTA_ID,MOTORISTA,ID,EFFECTIVE_AT,CURRENT_TIMESTAMP
FROM (
  SELECT
    REPLACE(REPLACE(UPPER(TRIM(PLACA)),'-',''),' ','') AS PLATE_KEY,
    VEICULO_ID,
    MOTORISTA_ID,
    MOTORISTA,
    ID,
    COALESCE(NULLIF(ATUALIZADO_EM,''),NULLIF(CRIADO_EM,''),DATA || ' 00:00:00') AS EFFECTIVE_AT,
    ROW_NUMBER() OVER (
      PARTITION BY REPLACE(REPLACE(UPPER(TRIM(PLACA)),'-',''),' ','')
      ORDER BY COALESCE(NULLIF(ATUALIZADO_EM,''),NULLIF(CRIADO_EM,''),DATA || ' 00:00:00') DESC,
               DATA DESC,
               ID DESC
    ) AS RN
  FROM ESCALAS_DIA
  WHERE TRIM(COALESCE(PLACA,''))<>''
    AND TRIM(COALESCE(MOTORISTA,''))<>''
    AND UPPER(TRIM(COALESCE(STATUS,'')))<>'CANCELADO'
)
WHERE RN=1
ON CONFLICT(PLATE) DO UPDATE SET
  VEHICLE_ID=excluded.VEHICLE_ID,
  DRIVER_ID=excluded.DRIVER_ID,
  DRIVER_NAME=excluded.DRIVER_NAME,
  SCHEDULE_ID=excluded.SCHEDULE_ID,
  EFFECTIVE_AT=excluded.EFFECTIVE_AT,
  UPDATED_AT=CURRENT_TIMESTAMP;
