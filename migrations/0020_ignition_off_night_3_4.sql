-- Sessões de ignição desligada no período noturno exclusivamente para veículos 3/4.
-- O relatório usa a duração real observada entre 20:00 e 05:00.
CREATE TABLE IF NOT EXISTS ROUTE_IGNITION_OFF_NIGHT (
  SESSION_KEY TEXT PRIMARY KEY,
  NIGHT_KEY TEXT NOT NULL,
  PLATE TEXT NOT NULL,
  VEHICLE_TYPE TEXT NOT NULL,
  SCHEDULE_ID TEXT,
  MONITORING_ID INTEGER,
  ROUTE TEXT,
  DRIVER_NAME TEXT,
  STARTED_AT TEXT NOT NULL,
  LAST_SEEN_AT TEXT NOT NULL,
  ENDED_AT TEXT,
  DURATION_MINUTES INTEGER NOT NULL DEFAULT 0,
  ACTIVE INTEGER NOT NULL DEFAULT 1,
  LOCATION_TEXT TEXT,
  LATITUDE REAL,
  LONGITUDE REAL,
  CREATED_AT TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP,
  UPDATED_AT TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS IDX_ROUTE_IGNITION_NIGHT_DATE ON ROUTE_IGNITION_OFF_NIGHT(NIGHT_KEY,PLATE,STARTED_AT);
CREATE INDEX IF NOT EXISTS IDX_ROUTE_IGNITION_NIGHT_ACTIVE ON ROUTE_IGNITION_OFF_NIGHT(ACTIVE,PLATE);
