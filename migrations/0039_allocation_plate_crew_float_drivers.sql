-- O vínculo operacional passa a ser por PLACA, sem rota.
-- As colunas legadas de rota/placa substituta permanecem para preservar histórico.
ALTER TABLE ROUTE_ALLOCATION_PLAN ADD COLUMN HELPER_ID TEXT;
ALTER TABLE ROUTE_ALLOCATION_PLAN ADD COLUMN HELPER_NAME TEXT;
CREATE INDEX IF NOT EXISTS IDX_ROUTE_ALLOC_PLAN_HELPER ON ROUTE_ALLOCATION_PLAN(HELPER_NAME,ACTIVE);

CREATE TABLE IF NOT EXISTS ROUTE_ALLOCATION_FLOAT_DRIVERS (
  ID TEXT PRIMARY KEY,
  DRIVER_ID TEXT NOT NULL,
  DRIVER_NAME TEXT NOT NULL,
  START_DATE TEXT NOT NULL,
  END_DATE TEXT,
  NOTES TEXT,
  ACTIVE INTEGER NOT NULL DEFAULT 1 CHECK (ACTIVE IN (0,1)),
  CREATED_BY INTEGER,
  CREATED_BY_NAME TEXT,
  CREATED_AT TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP,
  UPDATED_BY INTEGER,
  UPDATED_BY_NAME TEXT,
  UPDATED_AT TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS IDX_ROUTE_ALLOC_FLOAT_DRIVER_DATE ON ROUTE_ALLOCATION_FLOAT_DRIVERS(DRIVER_ID,START_DATE,END_DATE,ACTIVE);
