-- Cadastros exclusivos da Rota.
CREATE TABLE IF NOT EXISTS BASE_COLABORADORES (
  ID TEXT PRIMARY KEY,
  MATRICULA TEXT NOT NULL UNIQUE,
  NOME TEXT NOT NULL,
  FUNCAO TEXT NOT NULL,
  VINCULO TEXT,
  STATUS TEXT NOT NULL DEFAULT 'DISPONÍVEL',
  AJUDANTE_ROTA INTEGER NOT NULL DEFAULT 0 CHECK (AJUDANTE_ROTA IN (0,1)),
  CIDADE_ROTA TEXT,
  ROTAS_ATENDIDAS TEXT,
  FERIAS_INICIO TEXT,
  FERIAS_FIM TEXT,
  ANOMALIA TEXT,
  OBSERVACOES TEXT,
  UNIDADE TEXT,
  DATA_ADMISSAO TEXT,
  HORA_ENTRADA_PADRAO TEXT,
  JORNADA_CONTRATUAL_MIN INTEGER,
  ATIVO INTEGER NOT NULL DEFAULT 1 CHECK (ATIVO IN (0,1)),
  CRIADO_EM TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP,
  ATUALIZADO_EM TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP,
  USUARIO TEXT
);
CREATE INDEX IF NOT EXISTS IDX_ROUTE_COLAB_NOME ON BASE_COLABORADORES(NOME);
CREATE INDEX IF NOT EXISTS IDX_ROUTE_COLAB_FUNCAO_STATUS ON BASE_COLABORADORES(FUNCAO,STATUS,ATIVO);

CREATE TABLE IF NOT EXISTS BASE_VEICULOS (
  ID TEXT PRIMARY KEY,
  PLACA TEXT NOT NULL UNIQUE,
  TIPO TEXT,
  VINCULO TEXT,
  CAPACIDADE_TON REAL,
  STATUS TEXT NOT NULL DEFAULT 'DISPONÍVEL',
  LOCAL_ATUAL TEXT,
  TRANSPORTADORA TEXT,
  PERMITE_ROTA_COMERCIAL INTEGER NOT NULL DEFAULT 1 CHECK (PERMITE_ROTA_COMERCIAL IN (0,1)),
  MOTIVO_RESERVA TEXT,
  DATA_RESERVA TEXT,
  PREVISAO_PRONTO_MANUTENCAO TEXT,
  OBSERVACOES TEXT,
  ATIVO INTEGER NOT NULL DEFAULT 1 CHECK (ATIVO IN (0,1)),
  CRIADO_EM TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP,
  ATUALIZADO_EM TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP,
  USUARIO TEXT
);
CREATE INDEX IF NOT EXISTS IDX_ROUTE_VEICULO_STATUS ON BASE_VEICULOS(STATUS,ATIVO);

CREATE TABLE IF NOT EXISTS BASE_ROTAS (
  ID TEXT PRIMARY KEY,
  ROTA TEXT NOT NULL UNIQUE,
  REGIAO TEXT,
  PERFIL TEXT,
  TEMPO_IDA_MIN INTEGER,
  TEMPO_ENTRE_CIDADES_MIN INTEGER,
  TEMPO_VOLTA_MIN INTEGER,
  TEMPO_POR_ENTREGA_MIN INTEGER,
  DURACAO_DIAS INTEGER NOT NULL DEFAULT 1,
  DIAS_SEMANA TEXT,
  OBSERVACOES TEXT,
  ATIVO INTEGER NOT NULL DEFAULT 1 CHECK (ATIVO IN (0,1)),
  CRIADO_EM TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP,
  ATUALIZADO_EM TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP,
  USUARIO TEXT
);
CREATE INDEX IF NOT EXISTS IDX_ROUTE_ROTA_REGIAO ON BASE_ROTAS(REGIAO,ATIVO);
