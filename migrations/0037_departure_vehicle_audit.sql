CREATE TABLE IF NOT EXISTS ROUTE_DEPARTURE_AUDITS (
  ID INTEGER PRIMARY KEY AUTOINCREMENT,
  SCHEDULE_ID TEXT NOT NULL UNIQUE,
  DEPARTURE_ID INTEGER,
  DATE_KEY TEXT NOT NULL,
  PLATE TEXT,
  ROUTE TEXT,
  RESULT TEXT NOT NULL DEFAULT 'CONFORME',
  CHECKLIST_JSON TEXT NOT NULL,
  NOTES TEXT,
  AUDITOR_ID INTEGER,
  AUDITOR_NAME TEXT,
  AUDITED_AT TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CREATED_AT TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP,
  UPDATED_AT TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS IDX_ROUTE_DEPARTURE_AUDIT_DATE ON ROUTE_DEPARTURE_AUDITS(DATE_KEY,RESULT);
CREATE INDEX IF NOT EXISTS IDX_ROUTE_DEPARTURE_AUDIT_DEPARTURE ON ROUTE_DEPARTURE_AUDITS(DEPARTURE_ID);

CREATE TABLE IF NOT EXISTS ROUTE_DEPARTURE_AUDIT_PHOTOS (
  ID INTEGER PRIMARY KEY AUTOINCREMENT,
  AUDIT_ID INTEGER NOT NULL,
  FILE_NAME TEXT,
  MIME_TYPE TEXT NOT NULL,
  SIZE_BYTES INTEGER NOT NULL DEFAULT 0,
  CAPTION TEXT,
  STORAGE_KIND TEXT NOT NULL DEFAULT 'D1',
  OBJECT_KEY TEXT,
  DATA_BASE64 TEXT,
  CREATED_BY INTEGER,
  CREATED_AT TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS IDX_ROUTE_DEPARTURE_AUDIT_PHOTOS_AUDIT ON ROUTE_DEPARTURE_AUDIT_PHOTOS(AUDIT_ID,ID);
