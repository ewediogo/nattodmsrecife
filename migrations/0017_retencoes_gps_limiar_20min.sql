-- Retenções GPS e ajuste do limiar de ocorrência de parada para 20 minutos.
-- Retenções menores que 20 minutos passam a alimentar os indicadores sem abrir ocorrência.
CREATE TABLE IF NOT EXISTS ROUTE_GPS_RETENTIONS (
  RETENTION_KEY TEXT PRIMARY KEY,
  DATE_KEY TEXT NOT NULL,
  PLATE TEXT NOT NULL,
  ROUTE TEXT,
  DRIVER_NAME TEXT,
  SCHEDULE_ID TEXT,
  MONITORING_ID INTEGER,
  STARTED_AT TEXT NOT NULL,
  LAST_SEEN_AT TEXT NOT NULL,
  ENDED_AT TEXT,
  LOCATION_TEXT TEXT,
  LATITUDE REAL,
  LONGITUDE REAL,
  DURATION_MINUTES INTEGER NOT NULL DEFAULT 0,
  ACTIVE INTEGER NOT NULL DEFAULT 1,
  DATA_JSON TEXT,
  CREATED_AT TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP,
  UPDATED_AT TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS IDX_ROUTE_GPS_RET_DATE ON ROUTE_GPS_RETENTIONS(DATE_KEY,PLATE,STARTED_AT);
CREATE INDEX IF NOT EXISTS IDX_ROUTE_GPS_RET_ACTIVE ON ROUTE_GPS_RETENTIONS(ACTIVE,PLATE);

-- Ocorrências antigas que encerraram abaixo do novo limiar deixam de ser tratadas como pendência.
DELETE FROM ROUTE_GPS_OCCURRENCES
WHERE TYPE='PARADA_ACIMA_15_MIN' AND COALESCE(STOPPED_MINUTES,0)<20;

-- Mantém a chave histórica para preservar eventuais justificativas já vinculadas.
UPDATE ROUTE_GPS_OCCURRENCES
SET TYPE='PARADA_ACIMA_20_MIN',
    DETAILS=REPLACE(DETAILS,'acima de 15 minutos','a partir de 20 minutos'),
    UPDATED_AT=CURRENT_TIMESTAMP
WHERE TYPE='PARADA_ACIMA_15_MIN' AND COALESCE(STOPPED_MINUTES,0)>=20;
