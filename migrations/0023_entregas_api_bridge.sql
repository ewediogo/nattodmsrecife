-- Integração NATTO Entregas -> DMS-Rota real (Opção B)
-- Esta tabela é canônica somente para o ponto vinculado à rota.
-- Fotos/canhotos, chat, fila offline e detalhes de paradas continuam no banco do app Entregas.
CREATE TABLE IF NOT EXISTS ROUTE_TIME_CLOCK (
  ID INTEGER PRIMARY KEY AUTOINCREMENT,
  EVENT_KEY TEXT NOT NULL UNIQUE,
  SCHEDULE_ID TEXT NOT NULL,
  ROUTE_KEY TEXT,
  PLATE TEXT NOT NULL,
  EMPLOYEE_REGISTRATION TEXT,
  DRIVER_NAME TEXT,
  RECORD_TYPE TEXT NOT NULL,
  RECORDED_AT TEXT NOT NULL,
  APP_PHOTO_ID TEXT,
  APP_SESSION_ID TEXT,
  DETAILS_JSON TEXT NOT NULL DEFAULT '{}',
  CREATED_AT TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS IDX_ROUTE_TIME_CLOCK_SCHEDULE ON ROUTE_TIME_CLOCK(SCHEDULE_ID, RECORDED_AT);
CREATE INDEX IF NOT EXISTS IDX_ROUTE_TIME_CLOCK_DRIVER ON ROUTE_TIME_CLOCK(EMPLOYEE_REGISTRATION, RECORDED_AT);
