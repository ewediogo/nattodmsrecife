-- Escala e Central de Recursos.
CREATE TABLE IF NOT EXISTS ESCALAS_DIA (
  ID TEXT PRIMARY KEY,
  DATA TEXT NOT NULL,
  SEQUENCIA_CARREGAMENTO TEXT,
  CARGA TEXT,
  QTD_ENTREGAS INTEGER NOT NULL DEFAULT 0,
  PESO_CARGA_TON REAL NOT NULL DEFAULT 0,
  TEMPERATURA_FRIO_C REAL,
  HORA_SAIDA_PROGRAMADA TEXT,
  ROTA_ID TEXT,
  ROTA TEXT,
  DESTINO TEXT,
  REGIAO TEXT,
  DURACAO_DIAS INTEGER NOT NULL DEFAULT 1,
  VEICULO_ID TEXT,
  PLACA TEXT,
  MOTORISTA_ID TEXT,
  MOTORISTA TEXT,
  AJUDANTE_1_ID TEXT,
  AJUDANTE_1 TEXT,
  AJUDANTE_2_ID TEXT,
  AJUDANTE_2 TEXT,
  TIPO_EQUIPE TEXT,
  CARGA_FECHADA INTEGER NOT NULL DEFAULT 0,
  PREVISAO_TERMINO TEXT,
  PREVISAO_RETORNO TEXT,
  LIMITE_JORNADA TEXT,
  STATUS TEXT NOT NULL DEFAULT 'PROGRAMADO',
  OBSERVACOES TEXT,
  CRIADO_EM TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP,
  ATUALIZADO_EM TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP,
  USUARIO TEXT
);
CREATE INDEX IF NOT EXISTS IDX_ROUTE_ESCALA_DATA ON ESCALAS_DIA(DATA,STATUS);
CREATE INDEX IF NOT EXISTS IDX_ROUTE_ESCALA_RECURSOS ON ESCALAS_DIA(DATA,VEICULO_ID,MOTORISTA_ID);

CREATE TABLE IF NOT EXISTS DISPONIBILIDADE_RECURSOS (
  ID TEXT PRIMARY KEY,
  DATA_DISPONIBILIDADE TEXT NOT NULL,
  ESCALA_ORIGEM_ID TEXT,
  TIPO_RECURSO TEXT NOT NULL,
  RECURSO_ID TEXT NOT NULL,
  NOME TEXT,
  ORIGEM TEXT NOT NULL,
  STATUS TEXT NOT NULL DEFAULT 'DISPONÍVEL',
  OBSERVACOES TEXT,
  CRIADO_EM TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP,
  ATUALIZADO_EM TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP,
  USUARIO TEXT
);
CREATE INDEX IF NOT EXISTS IDX_ROUTE_AVAILABILITY_DATE_RESOURCE ON DISPONIBILIDADE_RECURSOS(DATA_DISPONIBILIDADE,TIPO_RECURSO,RECURSO_ID,STATUS);

CREATE TABLE IF NOT EXISTS RESERVAS_VEICULOS (
  ID TEXT PRIMARY KEY,
  VEICULO_ID TEXT NOT NULL,
  PLACA TEXT,
  DATA_INICIO TEXT NOT NULL,
  DATA_FIM TEXT,
  MOTIVO TEXT,
  STATUS TEXT NOT NULL DEFAULT 'ATIVA',
  OBSERVACOES TEXT,
  CRIADO_EM TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP,
  ATUALIZADO_EM TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP,
  USUARIO TEXT
);
CREATE INDEX IF NOT EXISTS IDX_ROUTE_RESERVA_VEICULO_DATA ON RESERVAS_VEICULOS(VEICULO_ID,DATA_INICIO,DATA_FIM,STATUS);

CREATE TABLE IF NOT EXISTS STATUS_DIARIO (
  ID TEXT PRIMARY KEY,
  DATA TEXT NOT NULL,
  TIPO_RECURSO TEXT NOT NULL,
  RECURSO_ID TEXT NOT NULL,
  MATRICULA TEXT,
  NOME TEXT,
  FUNCAO TEXT,
  VINCULO TEXT,
  STATUS TEXT NOT NULL,
  JUSTIFICATIVA TEXT,
  ORIGEM TEXT,
  PLACA TEXT,
  CRIADO_EM TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP,
  ATUALIZADO_EM TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP,
  USUARIO TEXT
);
CREATE INDEX IF NOT EXISTS IDX_ROUTE_STATUS_DIARIO ON STATUS_DIARIO(DATA,TIPO_RECURSO,RECURSO_ID,STATUS);

CREATE TABLE IF NOT EXISTS ROUTE_RESOURCE_EVENTS (
  ID INTEGER PRIMARY KEY AUTOINCREMENT,
  EVENT_KEY TEXT NOT NULL UNIQUE,
  RESOURCE_TYPE TEXT NOT NULL,
  RESOURCE_KEY TEXT NOT NULL,
  RESOURCE_ID TEXT,
  RESOURCE_NAME TEXT,
  STATUS TEXT NOT NULL,
  EFFECTIVE_AT TEXT NOT NULL,
  DATE_KEY TEXT NOT NULL,
  SOURCE TEXT NOT NULL,
  SOURCE_MODULE TEXT,
  SOURCE_RECORD_ID INTEGER,
  SCHEDULE_RECORD_ID INTEGER,
  DETAILS_JSON TEXT NOT NULL DEFAULT '{}',
  CREATED_BY INTEGER,
  CREATED_BY_NAME TEXT,
  CREATED_AT TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS IDX_ROUTE_RES_EVENT_RESOURCE ON ROUTE_RESOURCE_EVENTS(RESOURCE_TYPE,RESOURCE_KEY,EFFECTIVE_AT);
CREATE INDEX IF NOT EXISTS IDX_ROUTE_RES_EVENT_DATE ON ROUTE_RESOURCE_EVENTS(DATE_KEY,STATUS);
CREATE INDEX IF NOT EXISTS IDX_ROUTE_RES_EVENT_SOURCE ON ROUTE_RESOURCE_EVENTS(SOURCE_MODULE,SOURCE_RECORD_ID);
