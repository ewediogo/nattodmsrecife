CREATE TABLE IF NOT EXISTS ROUTE_REQUESTS (
  REQUEST_ID TEXT PRIMARY KEY,
  DOMAIN TEXT NOT NULL,
  RESPONSE_JSON TEXT,
  CREATED_AT TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS IDX_ROUTE_REQUEST_CREATED ON ROUTE_REQUESTS(CREATED_AT);

-- Armazenamento genérico interno, exclusivo do módulo Rota. Não é tabela de sincronização legada.
CREATE TABLE IF NOT EXISTS ROUTE_RECORDS (
  ID INTEGER PRIMARY KEY AUTOINCREMENT,
  MODULE TEXT NOT NULL,
  TITLE TEXT,
  STATUS TEXT,
  DATE_KEY TEXT,
  DATA_JSON TEXT NOT NULL,
  CREATED_BY INTEGER,
  UPDATED_BY INTEGER,
  CREATED_AT TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP,
  UPDATED_AT TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS IDX_ROUTE_REG_MODULE ON ROUTE_RECORDS(MODULE);
CREATE INDEX IF NOT EXISTS IDX_ROUTE_REG_DATE ON ROUTE_RECORDS(MODULE,DATE_KEY);
CREATE INDEX IF NOT EXISTS IDX_ROUTE_REG_STATUS ON ROUTE_RECORDS(MODULE,STATUS);
