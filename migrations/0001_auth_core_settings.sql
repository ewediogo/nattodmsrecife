-- Autenticação, auditoria, parâmetros, idempotência e locks.
PRAGMA foreign_keys = ON;

CREATE TABLE IF NOT EXISTS ROUTE_USERS (
  ID INTEGER PRIMARY KEY AUTOINCREMENT,
  NAME TEXT NOT NULL,
  EMAIL TEXT NOT NULL UNIQUE,
  MATRICULA TEXT,
  ROLE TEXT NOT NULL DEFAULT 'CONSULTA' CHECK (ROLE IN ('ADMIN','OPERADOR','CONSULTA')),
  CARGO TEXT,
  PASSWORD_HASH TEXT NOT NULL,
  SALT TEXT NOT NULL,
  ACTIVE INTEGER NOT NULL DEFAULT 1 CHECK (ACTIVE IN (0,1)),
  PERMISSIONS_JSON TEXT NOT NULL DEFAULT '[]',
  BASES_JSON TEXT NOT NULL DEFAULT '["route"]',
  MUST_CHANGE_PASSWORD INTEGER NOT NULL DEFAULT 0 CHECK (MUST_CHANGE_PASSWORD IN (0,1)),
  CREATED_AT TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP,
  UPDATED_AT TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP,
  LAST_LOGIN TEXT
);
CREATE UNIQUE INDEX IF NOT EXISTS IDX_ROUTE_USERS_MATRICULA ON ROUTE_USERS(MATRICULA) WHERE MATRICULA IS NOT NULL AND TRIM(MATRICULA)<>'';
CREATE INDEX IF NOT EXISTS IDX_ROUTE_USERS_EMAIL ON ROUTE_USERS(EMAIL);

CREATE TABLE IF NOT EXISTS ROUTE_SESSIONS (
  TOKEN TEXT PRIMARY KEY,
  USER_ID INTEGER NOT NULL,
  EXPIRES_AT TEXT NOT NULL,
  CREATED_AT TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP,
  FOREIGN KEY(USER_ID) REFERENCES ROUTE_USERS(ID) ON DELETE CASCADE
);
CREATE INDEX IF NOT EXISTS IDX_ROUTE_SESSION_EXPIRY ON ROUTE_SESSIONS(EXPIRES_AT);

CREATE TABLE IF NOT EXISTS ROUTE_AUDIT (
  ID INTEGER PRIMARY KEY AUTOINCREMENT,
  USER_ID INTEGER,
  USER_NAME TEXT,
  ACTION TEXT NOT NULL,
  MODULE TEXT,
  RECORD_ID INTEGER,
  DETAILS TEXT,
  CREATED_AT TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS IDX_ROUTE_AUDIT_MODULE ON ROUTE_AUDIT(MODULE,CREATED_AT);

CREATE TABLE IF NOT EXISTS CONFIGURACOES (
  CHAVE TEXT PRIMARY KEY,
  VALOR TEXT NOT NULL,
  TIPO TEXT,
  DESCRICAO TEXT,
  ATUALIZADO_EM TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP,
  USUARIO TEXT
);
