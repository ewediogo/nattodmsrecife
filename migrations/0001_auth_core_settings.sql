CREATE TABLE IF NOT EXISTS ROUTE_SCHEDULE_REQUESTS (
  REQUEST_ID TEXT PRIMARY KEY,
  RESPONSE_JSON TEXT,
  CREATED_AT TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP
);
