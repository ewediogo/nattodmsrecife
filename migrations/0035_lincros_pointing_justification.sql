-- Justificativas para usuários sem apontamento de entregas na Lincros.
CREATE TABLE IF NOT EXISTS ROUTE_LINCROS_POINTING_JUSTIFICATIONS (
  SCHEDULE_ID TEXT PRIMARY KEY,
  DATE_KEY TEXT,
  DRIVER_NAME TEXT,
  ROUTE TEXT,
  PLATE TEXT,
  JUSTIFICATION TEXT NOT NULL,
  UPDATED_BY INTEGER,
  UPDATED_BY_NAME TEXT,
  CREATED_AT TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP,
  UPDATED_AT TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS IDX_ROUTE_LINCROS_POINTING_JUST_DATE ON ROUTE_LINCROS_POINTING_JUSTIFICATIONS(DATE_KEY);
CREATE INDEX IF NOT EXISTS IDX_ROUTE_LINCROS_POINTING_JUST_DRIVER ON ROUTE_LINCROS_POINTING_JUSTIFICATIONS(DRIVER_NAME);
