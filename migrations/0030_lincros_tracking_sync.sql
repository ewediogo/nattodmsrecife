CREATE TABLE IF NOT EXISTS LINCROS_ROUTE_SYNC (
  ID INTEGER PRIMARY KEY AUTOINCREMENT,
  SCHEDULE_ID TEXT NOT NULL UNIQUE,
  DATE_KEY TEXT,
  PLATE TEXT,
  DMS_ROUTE TEXT,
  LINCROS_ROUTE_CODES TEXT NOT NULL DEFAULT '[]',
  DELIVERIES_PLANNED INTEGER NOT NULL DEFAULT 0,
  DELIVERIES_DONE INTEGER NOT NULL DEFAULT 0,
  DELIVERIES_RETURNED INTEGER NOT NULL DEFAULT 0,
  LATITUDE REAL,
  LONGITUDE REAL,
  POSITION_AT TEXT,
  DRIVER TEXT,
  STATUS TEXT,
  DISTANCE_PLANNED REAL,
  DISTANCE_ACTUAL REAL,
  RETENTION_MINUTES REAL,
  SOURCE_UPDATED_AT TEXT,
  CHECKED_AT TEXT,
  SYNCED_AT TEXT,
  DATA_HASH TEXT,
  LAST_ERROR TEXT,
  RAW_SUMMARY_JSON TEXT NOT NULL DEFAULT '{}'
);
CREATE INDEX IF NOT EXISTS IDX_LINCROS_SYNC_PLATE_DATE ON LINCROS_ROUTE_SYNC(PLATE,DATE_KEY);
CREATE INDEX IF NOT EXISTS IDX_LINCROS_SYNC_CHECKED ON LINCROS_ROUTE_SYNC(CHECKED_AT);

CREATE TABLE IF NOT EXISTS LINCROS_DELIVERIES (
  ID INTEGER PRIMARY KEY AUTOINCREMENT,
  SCHEDULE_ID TEXT NOT NULL,
  LINCROS_ROUTE_CODE TEXT,
  DELIVERY_CODE TEXT,
  CLIENT_CODE TEXT,
  CLIENT_NAME TEXT,
  SEQUENCE_PLANNED REAL,
  SEQUENCE_ACTUAL REAL,
  STATUS TEXT,
  DELIVERED INTEGER NOT NULL DEFAULT 0,
  RETURNED INTEGER NOT NULL DEFAULT 0,
  PENDING INTEGER NOT NULL DEFAULT 1,
  ARRIVED_AT TEXT,
  LEFT_AT TEXT,
  RETENTION_MINUTES REAL,
  RETENTION_SOURCE TEXT,
  DISTANCE_PLANNED REAL,
  DISTANCE_ACTUAL REAL,
  WEIGHT_DELIVERED REAL,
  WEIGHT_RETURNED REAL,
  LATITUDE REAL,
  LONGITUDE REAL,
  NOTES_JSON TEXT NOT NULL DEFAULT '[]',
  PROOF_URL TEXT,
  UPDATED_AT TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP,
  UNIQUE(SCHEDULE_ID,LINCROS_ROUTE_CODE,DELIVERY_CODE)
);
CREATE INDEX IF NOT EXISTS IDX_LINCROS_DELIVERIES_SCHEDULE ON LINCROS_DELIVERIES(SCHEDULE_ID,DELIVERED,PENDING);
