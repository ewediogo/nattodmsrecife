-- Plano de alocação Rota x veículo x motorista.
-- O plano é exclusivamente gerencial: não cria bloqueios na Escala.
CREATE TABLE IF NOT EXISTS ROUTE_ALLOCATION_PLAN (
  ID TEXT PRIMARY KEY,
  ROUTE_ID TEXT,
  ROUTE_NAME TEXT NOT NULL,
  REGION TEXT,
  VEHICLE_ID TEXT,
  PLATE TEXT NOT NULL,
  SUBSTITUTE_VEHICLE_ID TEXT,
  SUBSTITUTE_PLATE TEXT,
  DRIVER_ID TEXT,
  DRIVER_NAME TEXT NOT NULL,
  SUBSTITUTE_DRIVER_ID TEXT,
  SUBSTITUTE_DRIVER_NAME TEXT,
  START_DATE TEXT NOT NULL,
  END_DATE TEXT,
  NOTES TEXT,
  ACTIVE INTEGER NOT NULL DEFAULT 1 CHECK (ACTIVE IN (0,1)),
  CREATED_BY INTEGER,
  CREATED_BY_NAME TEXT,
  CREATED_AT TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP,
  UPDATED_BY INTEGER,
  UPDATED_BY_NAME TEXT,
  UPDATED_AT TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS IDX_ROUTE_ALLOC_PLAN_ROUTE_DATE ON ROUTE_ALLOCATION_PLAN(ROUTE_NAME,START_DATE,END_DATE,ACTIVE);
CREATE INDEX IF NOT EXISTS IDX_ROUTE_ALLOC_PLAN_PLATE ON ROUTE_ALLOCATION_PLAN(PLATE,SUBSTITUTE_PLATE,ACTIVE);
CREATE INDEX IF NOT EXISTS IDX_ROUTE_ALLOC_PLAN_DRIVER ON ROUTE_ALLOCATION_PLAN(DRIVER_NAME,SUBSTITUTE_DRIVER_NAME,ACTIVE);
