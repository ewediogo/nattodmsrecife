-- Estado persistente de movimento GPS para alertas operacionais da frota.
-- O contador de parada é reiniciado sempre que o veículo volta a se mover.
CREATE TABLE IF NOT EXISTS ROUTE_GPS_STATE (
  PLATE TEXT PRIMARY KEY,
  LAST_LATITUDE REAL,
  LAST_LONGITUDE REAL,
  LAST_GPS_AT TEXT,
  STATIONARY_SINCE TEXT,
  LAST_MOVEMENT_AT TEXT,
  LAST_SPEED REAL NOT NULL DEFAULT 0,
  LAST_IGNITION INTEGER NOT NULL DEFAULT 0,
  UPDATED_AT TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS IDX_ROUTE_GPS_STATE_LAST_GPS ON ROUTE_GPS_STATE(LAST_GPS_AT);
CREATE INDEX IF NOT EXISTS IDX_ROUTE_GPS_POSITIONS_TIME ON ROUTE_GPS_POSITIONS(GPS_TIME DESC);
