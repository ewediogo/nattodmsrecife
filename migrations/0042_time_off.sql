-- Folgas agendadas de motoristas e ajudantes (Gestão > Folgas).
-- Idempotente: a API também cria a tabela sob demanda (ensureTimeOffSchema).
CREATE TABLE IF NOT EXISTS ROUTE_TIME_OFF (
  ID TEXT PRIMARY KEY,
  EMPLOYEE_ID TEXT NOT NULL,
  EMPLOYEE_NAME TEXT NOT NULL DEFAULT '',
  EMPLOYEE_FUNCTION TEXT,
  START_DATE TEXT NOT NULL,
  END_DATE TEXT NOT NULL,
  REASON TEXT NOT NULL,
  NOTES TEXT,
  STATUS TEXT NOT NULL DEFAULT 'AGENDADA',
  CREATED_BY TEXT,
  CREATED_AT TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP,
  UPDATED_BY TEXT,
  UPDATED_AT TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CANCELED_BY TEXT,
  CANCELED_AT TEXT
);
CREATE INDEX IF NOT EXISTS IDX_ROUTE_TIME_OFF_EMPLOYEE ON ROUTE_TIME_OFF(EMPLOYEE_ID,START_DATE);
CREATE INDEX IF NOT EXISTS IDX_ROUTE_TIME_OFF_PERIOD ON ROUTE_TIME_OFF(START_DATE,END_DATE);
