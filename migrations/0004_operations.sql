-- Saídas, Monitoramento e Retornos. Sem campos de sincronização legada.
CREATE TABLE IF NOT EXISTS ROUTE_DEPARTURES (
  ID INTEGER PRIMARY KEY AUTOINCREMENT,
  SCHEDULE_ID TEXT,
  DATE_KEY TEXT NOT NULL,
  STATUS TEXT NOT NULL,
  PLATE TEXT,
  DRIVER_ID TEXT,
  DRIVER_NAME TEXT,
  ROUTE TEXT,
  REGION TEXT,
  PLANNED_AT TEXT,
  ACTUAL_AT TEXT,
  DELAY_MINUTES INTEGER NOT NULL DEFAULT 0,
  DATA_JSON TEXT NOT NULL,
  CREATED_BY INTEGER,
  UPDATED_BY INTEGER,
  CREATED_AT TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP,
  UPDATED_AT TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE UNIQUE INDEX IF NOT EXISTS IDX_ROUTE_DEPARTURE_SCHEDULE ON ROUTE_DEPARTURES(SCHEDULE_ID) WHERE SCHEDULE_ID IS NOT NULL AND SCHEDULE_ID<>'';
CREATE INDEX IF NOT EXISTS IDX_ROUTE_DEPARTURE_DATE ON ROUTE_DEPARTURES(DATE_KEY,STATUS);

CREATE TABLE IF NOT EXISTS ROUTE_MONITORING (
  ID INTEGER PRIMARY KEY AUTOINCREMENT,
  SCHEDULE_ID TEXT,
  DEPARTURE_ID INTEGER,
  DATE_KEY TEXT NOT NULL,
  STATUS TEXT NOT NULL,
  PLATE TEXT,
  DRIVER_NAME TEXT,
  ROUTE TEXT,
  VERSION INTEGER NOT NULL DEFAULT 1,
  DATA_JSON TEXT NOT NULL,
  CREATED_BY INTEGER,
  UPDATED_BY INTEGER,
  CREATED_AT TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP,
  UPDATED_AT TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE UNIQUE INDEX IF NOT EXISTS IDX_ROUTE_MONITORING_SCHEDULE ON ROUTE_MONITORING(SCHEDULE_ID) WHERE SCHEDULE_ID IS NOT NULL AND SCHEDULE_ID<>'';
CREATE INDEX IF NOT EXISTS IDX_ROUTE_MONITORING_DATE ON ROUTE_MONITORING(DATE_KEY,STATUS);

CREATE TABLE IF NOT EXISTS ROUTE_RETURNS (
  ID INTEGER PRIMARY KEY AUTOINCREMENT,
  SCHEDULE_ID TEXT,
  DEPARTURE_ID INTEGER,
  DATE_KEY TEXT NOT NULL,
  STATUS TEXT NOT NULL,
  PLATE TEXT,
  DRIVER_NAME TEXT,
  ROUTE TEXT,
  RETURN_AT TEXT,
  DATA_JSON TEXT NOT NULL,
  CREATED_BY INTEGER,
  UPDATED_BY INTEGER,
  CREATED_AT TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP,
  UPDATED_AT TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE UNIQUE INDEX IF NOT EXISTS IDX_ROUTE_RETURN_SCHEDULE ON ROUTE_RETURNS(SCHEDULE_ID) WHERE SCHEDULE_ID IS NOT NULL AND SCHEDULE_ID<>'';
CREATE INDEX IF NOT EXISTS IDX_ROUTE_RETURN_DATE ON ROUTE_RETURNS(DATE_KEY,STATUS);
