-- Ciclo CAJU 26 -> 25 e conferência/lançamento manual paralelo ao cálculo operacional.
INSERT OR IGNORE INTO CONFIGURACOES (CHAVE,VALOR,TIPO,DESCRICAO) VALUES
 ('CAJU_DIA_INICIO_CICLO','26','INTEGER','Dia de início do ciclo mensal do CAJU.'),
 ('CAJU_DIA_FIM_CICLO','25','INTEGER','Dia de término do ciclo mensal do CAJU.');

CREATE TABLE IF NOT EXISTS ROUTE_CAJU_MANUAL (
  ID INTEGER PRIMARY KEY AUTOINCREMENT,
  EMPLOYEE_ID TEXT NOT NULL,
  DATE_KEY TEXT NOT NULL,
  MANUAL_STATUS TEXT,
  CAJU_LANCADO INTEGER CHECK (CAJU_LANCADO IN (0,1) OR CAJU_LANCADO IS NULL),
  OBSERVACOES TEXT,
  CREATED_BY INTEGER,
  UPDATED_BY INTEGER,
  CREATED_AT TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP,
  UPDATED_AT TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP,
  UNIQUE(EMPLOYEE_ID,DATE_KEY)
);
CREATE INDEX IF NOT EXISTS IDX_ROUTE_CAJU_MANUAL_DATE ON ROUTE_CAJU_MANUAL(DATE_KEY,EMPLOYEE_ID);
