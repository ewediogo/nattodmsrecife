import fs from 'node:fs';
const root=new URL('..',import.meta.url).pathname.replace(/\/$/,'');
const pkg=JSON.parse(fs.readFileSync(`${root}/package.json`,'utf8'));
const indicators=fs.readFileSync(`${root}/functions/_lib/indicators.js`,'utf8');
const monitoring=fs.readFileSync(`${root}/functions/_lib/monitoring.js`,'utf8');
const route=fs.readFileSync(`${root}/public/assets/route.js`,'utf8');
const worker=fs.readFileSync(`${root}/public/_worker.js`,'utf8');
const assert=(condition,message)=>{if(!condition)throw new Error(message);};
assert(pkg.version==='1.0.158','Versão deve ser 1.0.105.');
assert(worker.includes("const VERSION='1.0.158'"),'Worker deve publicar 1.0.105.');
assert(indicators.includes('managementOvernightHistory'),'Backend deve consolidar histórico de pernoites.');
assert(indicators.includes("E.STATUS='PERNOITE'")&&indicators.includes("SOURCE,''))='MONITORAMENTO'"),'Histórico deve usar apontamentos reais do Monitoramento.');
assert(indicators.includes("includes('VAZIO')"),'Classificação de pernoite vazio deve procurar a palavra VAZIO.');
assert(indicators.includes('emptyOvernightVehicles'),'Indicador de veículos com pernoite vazio ausente.');
assert(monitoring.includes('justificativa_pernoite:record.justificativa_pernoite'),'Novos eventos devem preservar justificativa histórica.');
assert(monitoring.includes('sqliteUtcIso'),'Atualização do D1 deve ser normalizada como UTC.');
assert(route.includes('Histórico de pernoites apontados'),'Painel histórico ausente em Dados Gerenciais.');
assert(route.includes('route-mgt-overnight-export'),'Exportação CSV de pernoites ausente.');
assert(route.includes('Carros com pernoite vazio'),'Card de pernoite vazio ausente.');
assert(route.includes('auditDt(r.atualizadoEm)'),'Resumo deve exibir UPDATED_AT no fuso correto.');
console.log('OK v1.0.105: histórico de pernoites, pernoite vazio, CSV e fuso Recife validados.');
