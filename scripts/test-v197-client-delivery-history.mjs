import fs from 'node:fs';
const root=new URL('..',import.meta.url).pathname.replace(/\/$/,'');
const clients=fs.readFileSync(`${root}/functions/api/clients.js`,'utf8');
const lincros=fs.readFileSync(`${root}/functions/_lib/lincros.js`,'utf8');
const route=fs.readFileSync(`${root}/public/assets/route.js`,'utf8');
const migration=fs.readFileSync(`${root}/migrations/0031_lincros_client_history_index.sql`,'utf8');
const pkg=JSON.parse(fs.readFileSync(`${root}/package.json`,'utf8'));
const assert=(condition,message)=>{if(!condition)throw new Error(message);};
assert(pkg.version==='1.0.158','Versão do pacote deve ser 1.0.97.');
assert(clients.includes("clientLincrosHistoryByCodes"),'API de clientes não consulta o histórico Lincros no D1.');
assert(clients.includes('record.deliveryInfo=history.get'),'Resultados de clientes não recebem deliveryInfo.');
assert(lincros.includes('export async function clientLincrosHistoryByCodes'),'Helper de histórico por cliente ausente.');
assert(lincros.includes('D.PENDING=1')&&lincros.includes('D.DELIVERED=1'),'Consulta precisa separar pendências e entregas realizadas.');
assert(lincros.includes("EXISTS (SELECT 1 FROM ROUTE_MONITORING"),'Pendência atual precisa estar vinculada a rota aberta no DMS.');
assert(route.includes('PENDENTE NA ROTA ATUAL'),'Destaque de pendência atual ausente na Consulta de Clientes.');
assert(route.includes('Última entrega realizada'),'Bloco de última entrega ausente.');
assert(route.includes('Histórico recente de entregas realizadas'),'Histórico recente ausente.');
assert(route.includes('Dados Lincros armazenados no D1'),'Tela deve informar que usa cache D1.');
assert(route.includes('OC / NF')&&route.includes('Retenção')&&route.includes('Dist. planejada')&&route.includes('Dist. real'),'Detalhamento operacional incompleto.');
assert(migration.includes('IDX_LINCROS_DELIVERIES_CLIENT_STATE'),'Índice de histórico por cliente ausente.');
console.log('OK v1.0.97: Consulta de Clientes com pendência atual, última entrega e histórico D1 validada.');
